"""SQLAlchemy 2.x Database Engine, Models, and Migration Setup for Campaign Management.

Configured with SQLite by default (`sqlite:///data/campaigns.db`), reading `DATABASE_URL`
from the environment to enable zero-code PostgreSQL switching.
Strictly follows privacy rules: stores CustomerId only; NEVER stores Surname or personal fields.
"""
from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, field_validator
from sqlalchemy import (
    Boolean,
    Column,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    create_engine,
)
from sqlalchemy.orm import declarative_base, relationship, sessionmaker, Session

# Database URL resolution
DEFAULT_DB_PATH = Path(__file__).resolve().parents[2] / "data" / "campaigns.db"
DEFAULT_DB_PATH.parent.mkdir(parents=True, exist_ok=True)
DATABASE_URL = os.getenv("DATABASE_URL", f"sqlite:///{DEFAULT_DB_PATH}")

# SQLAlchemy engine & session factory
engine = create_engine(
    DATABASE_URL,
    connect_args={"check_same_thread": False} if DATABASE_URL.startswith("sqlite") else {},
    echo=False,
    future=True,
)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine, future=True)

Base = declarative_base()


# =============================================================================
# SQLAlchemy ORM Models
# =============================================================================

class CampaignModel(Base):
    """Campaign operational definition and metadata.
    
    Start and end dates are campaign administrative metadata, not dataset timeline.
    """
    __tablename__ = "campaigns"

    id = Column(Integer, primary_key=True, autoincrement=True)
    name = Column(String(255), unique=True, nullable=False, index=True)
    objective = Column(Text, nullable=False)
    target_segments = Column(Text, nullable=False)  # JSON-serialized list of segment names
    budget = Column(Float, nullable=False)
    allowed_actions = Column(Text, nullable=False)  # JSON-serialized list of action IDs
    start_date = Column(String(50), nullable=False)  # YYYY-MM-DD
    end_date = Column(String(50), nullable=False)    # YYYY-MM-DD
    status = Column(String(50), nullable=False, default="draft", index=True)  # draft, approved, active, completed, cancelled
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    updated_at = Column(DateTime, nullable=False, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships (selectin loading avoids DetachedInstanceError)
    targets = relationship("CampaignTargetModel", back_populates="campaign", cascade="all, delete-orphan", lazy="selectin")
    outcomes = relationship("OutcomeModel", back_populates="campaign", cascade="all, delete-orphan", lazy="selectin")

    __table_args__ = (
        Index("ix_campaigns_status_created", "status", "created_at"),
    )


class CampaignTargetModel(Base):
    """Individual customer assigned to a campaign action.
    
    Strictly stores customer_id only. No PII (Surname, Name, Address) is ever stored.
    """
    __tablename__ = "campaign_targets"

    id = Column(Integer, primary_key=True, autoincrement=True)
    campaign_id = Column(Integer, ForeignKey("campaigns.id", ondelete="CASCADE"), nullable=False, index=True)
    customer_id = Column(Integer, nullable=False, index=True)
    assigned_action = Column(String(100), nullable=False)
    status = Column(String(50), nullable=False, default="pending")  # pending, contacted, skipped, completed
    created_at = Column(DateTime, nullable=False, default=datetime.utcnow)

    campaign = relationship("CampaignModel", back_populates="targets")

    __table_args__ = (
        Index("ix_target_campaign_customer", "campaign_id", "customer_id", unique=True),
    )


class OutcomeModel(Base):
    """Realized campaign outcome per customer.
    
    Source distinguishes:
    - 'manual': entered manually by staff
    - 'uploaded': imported from operational CSV
    - 'simulated': generated by uplift response simulator
    """
    __tablename__ = "outcomes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    campaign_id = Column(Integer, ForeignKey("campaigns.id", ondelete="CASCADE"), nullable=False, index=True)
    customer_id = Column(Integer, nullable=False, index=True)
    contacted = Column(Boolean, nullable=False, default=True)
    responded = Column(Boolean, nullable=False, default=False)
    accepted = Column(Boolean, nullable=False, default=False)
    churned = Column(Boolean, nullable=False)  # True = exited / churned, False = retained
    recorded_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    recorded_by = Column(String(100), nullable=False, default="operator")
    source = Column(String(50), nullable=False)  # manual, uploaded, simulated

    campaign = relationship("CampaignModel", back_populates="outcomes")

    __table_args__ = (
        Index("ix_outcome_campaign_customer", "campaign_id", "customer_id"),
        Index("ix_outcome_source", "source"),
    )


class AuditLogModel(Base):
    """Immutable audit trail for all campaign lifecycle changes and destructive actions."""
    __tablename__ = "audit_log"

    id = Column(Integer, primary_key=True, autoincrement=True)
    entity_type = Column(String(100), nullable=False)  # campaign, campaign_target, outcome
    entity_id = Column(String(100), nullable=False)
    action = Column(String(100), nullable=False)        # CREATE, STATUS_CHANGE, CANCEL, DELETE, RECORD_OUTCOME
    old_state = Column(Text, nullable=True)            # JSON snapshot
    new_state = Column(Text, nullable=True)            # JSON snapshot
    user = Column(String(100), nullable=False, default="operator")
    timestamp = Column(DateTime, nullable=False, default=datetime.utcnow, index=True)


class SchemaVersionModel(Base):
    """Database schema migration version tracking."""
    __tablename__ = "schema_version"

    version = Column(Integer, primary_key=True)
    applied_at = Column(DateTime, nullable=False, default=datetime.utcnow)
    description = Column(String(255), nullable=False)


# =============================================================================
# Pydantic Schemas for Validation Before Writing
# =============================================================================

VALID_STATUSES = {"draft", "approved", "active", "completed", "cancelled"}
VALID_SOURCES = {"manual", "uploaded", "simulated"}


class CampaignCreate(BaseModel):
    name: str = Field(..., min_length=3, max_length=200)
    objective: str = Field(..., min_length=5)
    target_segments: List[str] = Field(..., min_length=1)
    budget: float = Field(..., gt=0)
    allowed_actions: List[str] = Field(..., min_length=1)
    start_date: str = Field(..., pattern=r"^\d{4}-\d{2}-\d{2}$")
    end_date: str = Field(..., pattern=r"^\d{4}-\d{2}-\d{2}$")

    @field_validator("end_date")
    @classmethod
    def validate_date_range(cls, v: str, info: Any) -> str:
        start = info.data.get("start_date")
        if start and v < start:
            raise ValueError(f"end_date ({v}) cannot be earlier than start_date ({start})")
        return v


class CampaignTargetCreate(BaseModel):
    customer_id: int = Field(..., gt=0)
    assigned_action: str = Field(..., min_length=2)


class OutcomeCreate(BaseModel):
    customer_id: int = Field(..., gt=0)
    contacted: bool = True
    responded: bool = False
    accepted: bool = False
    churned: bool  # True = churned, False = retained
    source: str = "manual"
    recorded_by: str = "operator"

    @field_validator("source")
    @classmethod
    def validate_source(cls, v: str) -> str:
        if v not in VALID_SOURCES:
            raise ValueError(f"source must be one of {VALID_SOURCES}, got '{v}'")
        return v


class AuditLogCreate(BaseModel):
    entity_type: str
    entity_id: str
    action: str
    old_state: Optional[Dict[str, Any]] = None
    new_state: Optional[Dict[str, Any]] = None
    user: str = "operator"


# =============================================================================
# Migration & Database Initialization
# =============================================================================

def init_db(target_engine=None) -> None:
    """Initialize database tables and record schema version.
    
    Safe to call repeatedly on startup. Applies migration v1 if not present.
    """
    db_engine = target_engine or engine
    Base.metadata.create_all(bind=db_engine)

    with Session(db_engine) as session:
        try:
            current = session.query(SchemaVersionModel).filter_by(version=1).first()
            if not current:
                v1 = SchemaVersionModel(
                    version=1,
                    applied_at=datetime.utcnow(),
                    description="v1: Initial schema for campaigns, targets, outcomes, audit_log"
                )
                session.add(v1)
                session.commit()
        except Exception:
            session.rollback()
            raise


def get_db_session() -> Session:
    """Provide a database session for repository calls."""
    return SessionLocal()
